function renderCurriculum(el, unit) {
  const rows = CURRICULUM[unit] || [];
  const mark = { ok: ['✓', 'נלמד ביחידה', 'var(--good)'], part: ['◐', 'בחלקו', 'var(--warn)'], other: ['↩', 'ביחידה אחרת', 'var(--muted)'], alt: ['–', 'לא בבחינה', 'var(--muted)'] };
  const n = rows.filter(r => r.st === 'ok').length;
  el.className = 'card info';
  el.innerHTML = `<h3>📋 תוכנית הלימודים: מה היחידה מכסה</h3>
   <p class="hint" style="margin:4px 0 10px">לפי תוכנית ההלימה בחקלאות, תחום בעלי חיים (שאלון 46381), ענפי בקר וצאן ועופות. ${n} סעיפים נלמדים ביחידה הזו.</p>
   <div class="tbl"><table><tr><th></th><th>סעיף</th><th>מה בתוכנית</th><th>איפה ביחידה</th></tr>
   ${rows.map(r => { const [s, lab, c] = mark[r.st]; return `<tr><td style="color:${c};font-weight:800;font-size:1.25em;text-align:center" title="${lab}" aria-label="${lab}">${s}</td><td>${r.sec}</td><td>${r.t}</td><td style="color:${r.st === 'ok' ? 'inherit' : 'var(--muted)'}">${r.w}</td></tr>` }).join('')}
   </table></div>`;
}
